"""Write dashboard artefacts (web/public/data) with the standard header, validated before writing.

Every part uses this module, so no file can reach the dashboard without passing its data contract
(implementation-plan.md §2.4) or while citing a source missing from the registry.
"""

from __future__ import annotations

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

from . import __version__
from .config import load_config, repo_path
from .contracts import schema_name_for, validate_document
from .sources import SOURCE_IDS, catalog

CONTRACT_VERSION = "1.0.0"
GENERATOR = f"freshpipe {__version__}"
DUBAI = timezone(timedelta(hours=4))  # Asia/Dubai has no daylight saving

PROVENANCE_LEGEND = {
    "REAL": "Unmodified real data; the source is cited.",
    "CALIBRATED_SYNTHETIC": "Generated by the project, with parameters calibrated to real sources.",
    "SCENARIO": "A what-if applied by the user.",
    "SIMULATED_FEED": "A precomputed stream replayed as if it were live.",
    "DERIVED": "Real factors applied to synthetic volumes.",
    "PRECOMPUTED": "Computed offline in the Python pipeline and served as static files.",
}


class ArtefactError(ValueError):
    """Raised when an artefact would violate its data contract."""


def header(provenance: str, sources: list[str], *, seed: int | None = None, is_fixture: bool = False) -> dict[str, Any]:
    """The header fields every artefact carries."""
    return {
        "contractVersion": CONTRACT_VERSION,
        "generatedAt": datetime.now(DUBAI).replace(microsecond=0).isoformat(),
        "generator": GENERATOR,
        "seed": seed,
        "isFixture": is_fixture,
        "provenance": provenance,
        "sources": sources,
    }


def write_artefact(
    relative_path: str,
    body: dict[str, Any],
    *,
    provenance: str,
    sources: list[str],
    seed: int | None = None,
    pretty: bool = False,
    root: Path | None = None,
) -> Path:
    """Validate `header + body` against the contract for `relative_path`, then write it.

    `root` defaults to web/public/data. Raises ArtefactError instead of writing an invalid file.
    """
    unknown = sorted(set(sources) - SOURCE_IDS)
    if unknown:
        raise ArtefactError(f"{relative_path}: unknown source ids {unknown}")
    schema = schema_name_for(relative_path)
    if schema is None:
        raise ArtefactError(f"{relative_path}: no data contract matches this path")
    document = header(provenance, sources, seed=seed) | body
    errors = validate_document(document, schema)
    if errors:
        raise ArtefactError(f"{relative_path} violates the '{schema}' contract:\n  " + "\n  ".join(errors[:20]))
    target = (root or repo_path("web_data")) / relative_path
    target.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(document, indent=2 if pretty else None, separators=None if pretty else (",", ":"),
                      ensure_ascii=False)
    target.write_text(text + "\n", encoding="utf-8", newline="\n")
    return target


def write_meta(root: Path | None = None) -> Path:
    """Write meta.json from the source registry and pipeline/config.yaml."""
    config = load_config()
    body = {
        "project": "Fresh Control Tower",
        "operatorName": config.get("operator_name", "The Operator (fictional)"),
        "operatorIsFictional": True,
        "timezone": "Asia/Dubai",
        "currency": "AED",
        "horizon": {"start": config["horizon"]["start"], "end": config["horizon"]["end"]},
        "testWindow": {"start": config["splits"]["test_start"], "end": config["horizon"]["end"]},
        "sourcesCatalog": catalog(),
        "provenanceLegend": PROVENANCE_LEGEND,
    }
    return write_artefact("meta.json", body, provenance="PRECOMPUTED", sources=[], pretty=True, root=root)
